from dataclasses import dataclass
from enum import Enum
class Role(str, Enum):
 PLATFORM_ADMIN="PLATFORM_ADMIN"
 INSTITUTION_ADMIN="INSTITUTION_ADMIN"
 ISSUER="ISSUER"
 STUDENT="STUDENT"
 PUBLIC_VERIFIER="PUBLIC_VERIFIER"
class Permission(str, Enum):
 PUBLIC_VERIFY="PUBLIC_VERIFY"
 ISSUE_CERTIFICATE="ISSUE_CERTIFICATE"
 CORRECT_CERTIFICATE="CORRECT_CERTIFICATE"
 BATCH_ADMINISTRATION="BATCH_ADMINISTRATION"
 REVOKE_CERTIFICATE="REVOKE_CERTIFICATE"
 MANAGE_INSTITUTION_USERS="MANAGE_INSTITUTION_USERS"
 MANAGE_INSTITUTIONS="MANAGE_INSTITUTIONS"
 CHANGE_ROLES="CHANGE_ROLES"
@dataclass(frozen=True)
class User:
 id:int
 email:str
 display_name:str
 role:Role
 institution_id:int|None
 active:bool
 roll_number:str|None=None
